export type LocaleMode = 'auto' | 'en' | 'zh'
export type ActiveLocale = 'en' | 'zh'

const STORAGE_KEY = 'dataforge.locale'

function pickLocale(tag: string): ActiveLocale {
  return tag.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

function readMode(): LocaleMode {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'auto' || saved === 'en' || saved === 'zh') return saved
  } catch {
    // localStorage can be unavailable in a sandboxed frame.
  }
  return 'auto'
}

const mode = ref<LocaleMode>(readMode())
const hostLocale = ref('')

const active = computed<ActiveLocale>(() =>
  mode.value === 'auto' ? pickLocale(hostLocale.value || browserLocale()) : mode.value,
)

function browserLocale(): string {
  return typeof navigator === 'undefined' ? 'en' : navigator.language
}

function interpolate(template: string, values?: Record<string, string | number>): string {
  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    values[key] === undefined ? match : String(values[key]),
  )
}

export function t(key: MessageKey, values?: Record<string, string | number>): string {
  const table = active.value === 'zh' ? zh : en
  return interpolate(table[key] ?? en[key], values)
}

export function applyDocumentLang(): void {
  document.documentElement.lang = active.value === 'zh' ? 'zh-CN' : 'en'
}

export function setHostLocale(locale: string | undefined): void {
  hostLocale.value = locale ?? ''
  applyDocumentLang()
}

export function setLocaleMode(next: LocaleMode): void {
  mode.value = next
  try {
    localStorage.setItem(STORAGE_KEY, next)
  } catch {
    // Persistence is best effort.
  }
  applyDocumentLang()
}

export function nextLocaleMode(current: LocaleMode): LocaleMode {
  if (current === 'auto') return 'en'
  if (current === 'en') return 'zh'
  return 'auto'
}

export const localeMode = mode
export const activeLocale = active

export function localeLabel(current: LocaleMode): string {
  if (current === 'zh') return t('lang.chinese')
  if (current === 'en') return t('lang.english')
  return t('lang.auto')
}
